import express from 'express';
import cors from 'cors';
import helmet from 'helmet';
import rateLimit from 'express-rate-limit';
import authRoutes from './routes/auth.js';
import workerRoutes from './routes/workers.js';
import jobRoutes from './routes/jobs.js';
import bookingRoutes from './routes/bookings.js';
import reviewRoutes from './routes/reviews.js';
import reportRoutes from './routes/reports.js';
const app=express();
app.use(helmet());
app.use(cors({origin:process.env.CLIENT_URL?.split(',')||'http://localhost:5173'}));
app.use(express.json({limit:'1mb'}));
app.get('/health',(req,res)=>res.json({success:true,data:{status:'ok',service:'kaamconnect-api',time:new Date().toISOString()}}));
app.get('/api/health',(req,res)=>res.json({success:true,data:{status:'ok'}}));
app.use('/api/auth',rateLimit({windowMs:15*60*1000,limit:100,standardHeaders:true,legacyHeaders:false}),authRoutes);
app.use('/api/workers',workerRoutes);app.use('/api/jobs',jobRoutes);app.use('/api/bookings',bookingRoutes);app.use('/api/reviews',reviewRoutes);app.use('/api/reports',reportRoutes);
app.use((req,res)=>res.status(404).json({success:false,error:{code:'NOT_FOUND',message:'API endpoint not found.'}}));
app.use((err,req,res,next)=>{console.error(err);const status=err.name==='ZodError'?400:err.code===11000?409:500;res.status(status).json({success:false,error:{code:err.name==='ZodError'?'VALIDATION_ERROR':'SERVER_ERROR',message:status===500?'Something went wrong.':err.message}});});
export default app;
